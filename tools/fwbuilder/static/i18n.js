function detectLang() {
  try {
    const saved = localStorage.getItem("fwb.lang");
    if (saved === "cs" || saved === "en") return saved;
  } catch (e) { /* storage blocked: fall back to the browser */ }
  const langs = navigator.languages || [navigator.language || "en"];
  return langs.some((l) => /^(cs|sk)\b/i.test(l)) ? "cs" : "en";
}

let LANG = detectLang();

function t(key, ...args) {
  const text = (STRINGS[LANG] && STRINGS[LANG][key]) || STRINGS.en[key] || key;
  return text.replace(/\{(\d+)\}/g, (_, i) => (args[i] !== undefined ? args[i] : ""));
}

function applyStatic() {
  document.documentElement.lang = LANG;
  document.querySelectorAll("[data-i18n]").forEach((n) => { n.textContent = t(n.dataset.i18n); });
  document.querySelectorAll("[data-i18n-ph]").forEach((n) => { n.placeholder = t(n.dataset.i18nPh); });
  document.querySelectorAll("[data-i18n-title]").forEach((n) => { n.title = t(n.dataset.i18nTitle); });
}
